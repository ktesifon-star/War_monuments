let savedLanguage;
try { savedLanguage = localStorage.getItem('memorial-language'); } catch {}
const requestedLanguage = new URLSearchParams(location.search || '').get('lang');
export const language = requestedLanguage === 'kk' || requestedLanguage === 'ru'
  ? requestedLanguage : savedLanguage === 'kk' ? 'kk' : 'ru';
const phrases = Object.keys(translations).sort((a, b) => b.length - a.length);
const pattern = new RegExp(phrases.map(text => text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|'), 'g');
export function translate(text) {
  return language === 'kk' ? String(text).replace(pattern, match => translations[match]) : text;
}
export function localizeRecords(records) {
  if (!Array.isArray(records)) return records;
  return records.map(item => {
    if (!item || typeof item !== 'object') return item;
    const aliases = [item.name, item.location, item.region, item.kk?.name, item.kk?.location, item.kk?.region].filter(Boolean).join(' ');
    return {...item, ...(language === 'kk' ? item.kk : {}), searchAliases: aliases};
  });
}
export function initializeLanguage() {
  if (!document.querySelectorAll) return;
  document.documentElement.lang = language;
  try { localStorage.setItem('memorial-language', language); } catch {}
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) {
    const text = walker.currentNode;
    if (!text.parentElement.closest('script, style, svg')) text.nodeValue = translate(text.nodeValue);
  }
  document.title = translate(document.title);
  document.querySelectorAll('[aria-label], [placeholder], meta[name="description"]').forEach(element => {
    for (const attribute of ['aria-label', 'placeholder', 'content']) {
      if (element.hasAttribute(attribute)) element.setAttribute(attribute, translate(element.getAttribute(attribute)));
    }
  });
  document.querySelectorAll('[data-language]').forEach(link => {
    const target = link.dataset.language;
    link.setAttribute('aria-current', target === language ? 'true' : 'false');
    link.addEventListener('click', event => {
      event.preventDefault();
      const url = new URL(location.href);
      url.searchParams.set('lang', target);
      location.assign(url.href);
    });
  });
}
